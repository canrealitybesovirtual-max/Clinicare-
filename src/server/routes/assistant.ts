/**
 * POST /api/assistant  body: AssistInput (src/server/ai/schemas.ts)  -> AssistResult, labeled "For clinician review".
 * The optional Claude assistant (owner amendment, CLAUDE.md 2026-11-27). OFF unless ANTHROPIC_API_KEY,
 * AI_ASSISTANT_ENABLED=true and AI_BAA_CONFIRMED=true are all set on the server; otherwise 503 "not-configured"
 * with a friendly message, before the body is read. Order: enabled -> per-client limit -> body -> PHI / Part 2
 * / reference-text checks -> one SDK call. Nothing is logged.
 * Wire as: src/app/api/assistant/route.ts -> export { POST } from "@/server/routes/assistant"; export const runtime = "nodejs";
 */
import { NextResponse } from "next/server";
import { OutboundRejected } from "@/lib/outbound";
import { NotConfigured, RequestRejected, fail, ok, type ApiErr } from "@/server/core";
import { ReferenceTextWithheld, SubstanceUseWithheld, assistFollowUp, type AssistDeps } from "@/server/ai/assistant";
import { isAssistantEnabled } from "@/server/ai/config";
import { takeAssistantToken } from "@/server/ai/limits";
import { readAssistantJson } from "@/server/ai/request";

export const runtime = "nodejs";

export const ASSISTANT_ATTRIBUTION = "Generated by Claude (Anthropic) for clinician review. Not a diagnosis or risk assessment.";
export const ASSISTANT_SOURCE = "Anthropic API";

export const ASSISTANT_MESSAGES = {
  off: "The optional AI assistant is turned off on this server. Everything else in the app works without it.",
  identifiers:
    "Possible identifiers were found (names, including names typed in lower case, dates, places, numbers, also spelled out). Remove them and try again. Nothing was sent.",
  reference:
    "The note seems to quote or cite diagnostic-manual criteria or treatment-planner text. The assistant never receives that text. Describe what you observed in your own words and try again. Nothing was sent.",
  substance:
    "Substance-use details, including alcohol or drug withdrawal, are never sent to the assistant (42 CFR Part 2). Remove them from the note and try again. Nothing was sent; the app's on-device tools still cover them.",
} as const;

const noStore = { "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff" };
const err = (status: number, code: ApiErr["code"], error: string) =>
  NextResponse.json<ApiErr>({ ok: false, error, code }, { status, headers: noStore });

/** Friendly messages for the assistant's own refusals; everything else maps through core's fail(). */
export function assistantFail(e: unknown) {
  if (e instanceof NotConfigured) return err(503, "not-configured", ASSISTANT_MESSAGES.off);
  if (e instanceof SubstanceUseWithheld) return err(400, "rejected", ASSISTANT_MESSAGES.substance);
  if (e instanceof ReferenceTextWithheld) return err(400, "rejected", ASSISTANT_MESSAGES.reference);
  if (e instanceof OutboundRejected) return err(400, "rejected", ASSISTANT_MESSAGES.identifiers);
  return fail(e);
}

/** The handler with injectable dependencies (tests pass a fake SDK client and env). */
export function createAssistantHandler(deps: AssistDeps = {}) {
  return async function POST(req: Request) {
    try {
      if (!isAssistantEnabled(deps.env ?? process.env)) throw new NotConfigured("The AI assistant");
      if (!takeAssistantToken(req)) throw new RequestRejected(429, "Too many assistant requests, try again in a minute");
      const body = await readAssistantJson(req);
      return ok(await assistFollowUp(body, deps), ASSISTANT_ATTRIBUTION, ASSISTANT_SOURCE);
    } catch (e) {
      return assistantFail(e);
    }
  };
}

export const POST = createAssistantHandler();
