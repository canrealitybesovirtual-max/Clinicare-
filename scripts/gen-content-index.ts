/**
 * Generates one module per content folder under src/lib/generated/ (conditions.ts, handouts.ts, ...): static
 * imports of every JSON file in that folder, so server and client bundles load content without filesystem
 * access. One module per folder keeps client bundles small: a client component that reaches content.ts pulls
 * in only the folders content.ts imports (conditions, handouts, measures), never interventions, plans, ethics
 * or legal, which bundlers do not drop from a shared module even when unused.
 * Run after adding or removing content files (npm run gen:content). CI fails if a committed module is stale
 * (tests/unit/content-index.test.ts).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "..");
export const GENERATED_DIR = path.join(root, "src/lib/generated");
export const CONTENT_DIRS = ["conditions", "measures", "handouts", "interventions", "plans", "ethics", "legal"] as const;
export type ContentDir = (typeof CONTENT_DIRS)[number];

const HEADER = "// AUTO-GENERATED by scripts/gen-content-index.ts. Do not edit by hand: run `npm run gen:content`.";

/** JSON file names in content/<dir>, sorted. */
export function contentFiles(dir: ContentDir): string[] {
  const abs = path.join(root, "content", dir);
  return existsSync(abs) ? readdirSync(abs).filter((f) => f.endsWith(".json")).sort() : [];
}

/** Source of src/lib/generated/<dir>.ts: `export const <dir>Raw: unknown[]` in file-name order. */
export function renderModule(dir: ContentDir): string {
  const files = contentFiles(dir);
  const imports = files.map((f, i) => `import c${i} from "@content/${dir}/${f}";`);
  const list = files.map((_, i) => `c${i}`).join(", ");
  return [HEADER, "/* eslint-disable */", ...imports, "", `export const ${dir}Raw: unknown[] = [${list}];`, ""].join("\n");
}

if (require.main === module) {
  const written: string[] = [];
  for (const dir of CONTENT_DIRS) {
    const out = path.join(GENERATED_DIR, `${dir}.ts`);
    const next = renderModule(dir);
    if (!existsSync(out) || readFileSync(out, "utf8") !== next) {
      writeFileSync(out, next);
      written.push(dir);
    }
  }
  console.log(`content index: ${written.length ? `written ${written.join(", ")}` : "unchanged"}`);
}
