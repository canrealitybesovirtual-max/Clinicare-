/**
 * Generates src/lib/generated/content-index.ts: static imports of every content JSON file so both server and
 * client bundles can load the library without filesystem access. Run after adding/removing content files
 * (npm run gen:content). CI fails if the committed index is stale (tests/unit/content-index.test.ts).
 */
import { readdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import path from "node:path";

const root = path.resolve(__dirname, "..");
const DIRS = ["conditions", "interventions", "plans", "handouts", "ethics", "legal"] as const;

export function renderIndex(): string {
  const lines: string[] = [
    "// AUTO-GENERATED by scripts/gen-content-index.ts. Do not edit by hand: run `npm run gen:content`.",
    "/* eslint-disable */",
  ];
  const exports: string[] = [];
  let n = 0;
  for (const dir of DIRS) {
    const abs = path.join(root, "content", dir);
    const files = existsSync(abs) ? readdirSync(abs).filter((f) => f.endsWith(".json")).sort() : [];
    const names: string[] = [];
    for (const f of files) {
      const name = `c${n++}`;
      names.push(name);
      lines.push(`import ${name} from "@content/${dir}/${f}";`);
    }
    exports.push(`export const ${dir}Raw: unknown[] = [${names.join(", ")}];`);
  }
  return [...lines, "", ...exports, ""].join("\n");
}

if (require.main === module) {
  const out = path.join(root, "src/lib/generated/content-index.ts");
  const next = renderIndex();
  const prev = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (prev !== next) writeFileSync(out, next);
  console.log(`content index: ${prev === next ? "unchanged" : "written"}`);
}
